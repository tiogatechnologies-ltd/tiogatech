// Regenerates supabase/functions/_shared/catalog-prices.ts from the storefront
// catalog (src/data/*.ts), so the edge functions know what each product costs.
//
//   npm run catalog:prices
//
// Re-run it whenever products or prices change, then redeploy paystack-init.
// A unit test fails if the committed file is out of date.
import { build } from "esbuild";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const entry = `
import { PRODUCTS } from "./src/data/products";
import { buildStaticPriceMap } from "./supabase/functions/_shared/pricing";
export const prices = buildStaticPriceMap(PRODUCTS);
`;

const result = await build({
  stdin: { contents: entry, resolveDir: process.cwd(), loader: "ts" },
  bundle: true,
  platform: "node",
  format: "esm",
  write: false,
  logLevel: "error",
});

const dir = mkdtempSync(join(tmpdir(), "catalog-prices-"));
const file = join(dir, "bundle.mjs");
writeFileSync(file, result.outputFiles[0].text);
const { prices } = await import(pathToFileURL(file).href);

const body = Object.entries(prices)
  .map(([name, price]) => `  ${JSON.stringify(name)}: ${price},`)
  .join("\n");

const out = `// GENERATED by scripts/generate-catalog-prices.mjs - do not edit by hand.
// Normalised product name -> selling price in NGN, used by paystack-init to check
// an order's total against what its items cost. Run \`npm run catalog:prices\`
// after any catalog or price change.
export const CATALOG_PRICES: Record<string, number> = {
${body}
};
`;

writeFileSync("supabase/functions/_shared/catalog-prices.ts", out);
console.log(`wrote ${Object.keys(prices).length} prices to supabase/functions/_shared/catalog-prices.ts`);
